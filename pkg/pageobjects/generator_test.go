func makeManifest(t *testing.T, tmpl string) (*analysis.ProjectManifest, string) {
	t.Helper()
	tmpDir := t.TempDir()
	manifest := &analysis.ProjectManifest{
		Components: map[string]*analysis.Component{
			"example.Foo": {
				TypeName:    "Foo",
				PackageName: "mypkg",
				PackagePath: "example",
				SourceFile:  filepath.Join(tmpDir, "foo.go"),
				Template:    &tmpl,
			},
		},
	}
	return manifest, tmpDir
}

// TestGenerateFromManifest_output_path verifies that the generator writes
// <stem>_browser.gen.go in the same directory as SourceFile.
func TestGenerateFromManifest_output_path(t *testing.T) {
	tmpDir := t.TempDir()
	tmpl := `<div>hello</div>`
	manifest := &analysis.ProjectManifest{
		Components: map[string]*analysis.Component{
			"example.Foo": {
				TypeName:    "Foo",
				PackageName: "mypkg",
				PackagePath: "example",
				SourceFile:  filepath.Join(tmpDir, "foo.go"),
				Template:    &tmpl,
			},
		},
	}

	written, err := pageobjects.GenerateFromManifest(manifest, pageobjects.StaticConfig{Tag: "browser"})
	require.NoError(t, err)
	require.Len(t, written, 1)

	expected := filepath.Join(tmpDir, "foo_browser.gen.go")
	require.Equal(t, expected, written[0])

	_, statErr := os.Stat(expected)
	require.NoError(t, statErr)
}

// TestGenerateFromManifest_header verifies the generated file header and package declaration.
